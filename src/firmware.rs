// The entries of a CPC's firmware jumpblocks by the names SOFT 968, The
// Amstrad 6128 Firmware Manual, gives them, in the lists of its section 14,
// https://archive.org/details/SOFT968TheAmstrad6128FirmwareManual. Its
// section 15 heads entry 23 KM ARM BREAKS where section 14 lists KM ARM
// BREAK.

// "Three versions of the firmware are described. V1.0 (on CPC464), V1.1 (on
// CPC664) and V1.2 (on CPC6128)." (SOFT 968, 1)
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Version {
    V1_0,
    V1_1,
    V1_2,
}

pub const VERSIONS: [Version; 3] = [Version::V1_0, Version::V1_1, Version::V1_2];

// Entries three bytes apart, an empty name for a number with none, and how
// many of the names each version runs to, V1.0's, V1.1's and V1.2's in turn:
// a later version adds entries only after the earlier's last.
struct Jumpblock {
    first: u16,
    names: &'static [&'static str],
    counts: [usize; 3],
}

