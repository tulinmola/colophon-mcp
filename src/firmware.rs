const JUMPBLOCKS: [Jumpblock; 3] = [
    Jumpblock {
        first: 0xB900,
        names: &HIGH_KERNEL,
        counts: [12, 15, 15],
    },
    Jumpblock {
        first: 0xBB00,
        names: &MAIN,
        counts: [190, 201, 202],
    },
    Jumpblock {
        first: 0xBDCD,
        names: &INDIRECTIONS,
        counts: [13, 14, 14],
    },
];

// The name of the entry at an address in a version's jumpblocks, if one is.
pub fn entry(version: Version, address: u16) -> Option<&'static str> {
    entries(version).find_map(|(at, name)| (at == address).then_some(name))
}

pub fn entries(version: Version) -> impl Iterator<Item = (u16, &'static str)> {
    JUMPBLOCKS.iter().flat_map(move |jumpblock| {
        (0..)
            .zip(&jumpblock.names[..jumpblock.counts[version as usize]])
            .filter(|(_, name)| !name.is_empty())
            .map(|(number, name)| (jumpblock.first + 3 * number, *name))
    })
}
